"""Emit the deployed bposit8 -> int8 codebook as a C header.

Reproduces build_bposit8_to_int8_lut() from the GPU kernel exactly: the value
times 2^96 is arithmetic-shifted right by (96 - SCALE_BITS), i.e. floored onto
the 2^-SCALE_BITS grid, then saturated into int8.
"""
import sys, os
from fractions import Fraction

# bposit16_reference.py (Apache-2.0) ships with github.com/anomly-labs/mosyne-bposit under
# kernels/. Set BPOSIT16_REFERENCE_DIR, or clone mosyne-bposit beside this repository.
sys.path.insert(0, os.environ.get("BPOSIT16_REFERENCE_DIR", os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "..", "mosyne-bposit", "kernels")))
from bposit16_reference import decode_bposit8, decoded_to_fraction_8

SCALE_BITS = 6
lut = []
for c in range(256):
    d = decode_bposit8(c)
    if d.is_special == "nar":
        lut.append(0)          # NaR contributes nothing; the deployed LUT maps it to 0
        continue
    v = decoded_to_fraction_8(d)
    x = v * Fraction(1 << SCALE_BITS)
    # floor toward -inf (arithmetic shift), then saturate
    q = x.numerator // x.denominator
    lut.append(max(-128, min(127, q)))

print("// Copyright (c) 2026 Anomly, Inc. All rights reserved. Author: Ry Bruscoe.")
print("// Generated by gen_bposit8_int8_lut.py -- do not edit by hand.")
print(f"// bposit8 (eS=2) -> int8 fixed point at scale 2^-{SCALE_BITS}.")
print("#pragma once")
print("#include <cstdint>")
print(f"constexpr int BP8_SCALE_BITS = {SCALE_BITS};")
print("static const std::int8_t kBposit8ToInt8[256] = {")
for i in range(0, 256, 16):
    print("    " + ", ".join(f"{v:4d}" for v in lut[i:i+16]) + ",")
print("};")
